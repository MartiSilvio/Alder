            sb.AppendLine("        }");
        }
        else
        {
            sb.AppendLine("        return false;");
        }

        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static void EmitTryGetIndex(StringBuilder sb, TypeRegistrationModel reg)
    {
        var readableIndexers = reg.Indexers.Where(i => i.CanRead).ToArray();

        sb.AppendLine("    public bool TryGetIndex(object instance, object key, out object? value)");
        sb.AppendLine("    {");

        if (readableIndexers.Length > 0)
        {
            var idx = readableIndexers[0];
            sb.AppendLine($"        value = (({reg.TypeFullName})instance)[({idx.KeyTypeFullName})key];");
            sb.AppendLine("        return true;");
        }
        else
        {
            sb.AppendLine("        value = default;");
            sb.AppendLine("        return false;");
        }

        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static void EmitTrySetIndex(StringBuilder sb, TypeRegistrationModel reg)
    {
        var writableIndexers = reg.Indexers.Where(i => i.CanWrite).ToArray();

        sb.AppendLine("    public bool TrySetIndex(object instance, object key, object? value)");
        sb.AppendLine("    {");

        if (writableIndexers.Length > 0)
        {
            var idx = writableIndexers[0];
            sb.AppendLine($"        (({reg.TypeFullName})instance)[({idx.KeyTypeFullName})key] = ({idx.ValueTypeFullName})value!;");
            sb.AppendLine("        return true;");
        }
        else
        {
            sb.AppendLine("        return false;");
        }

        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static void EmitTryGetStaticProperty(StringBuilder sb, TypeRegistrationModel reg)
