using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using CsEval.Generators.Model;

namespace CsEval.Generators.Emitters;

internal static class TypeMetadataEmitter
{
    public static string Emit(TypeRegistrationModel reg)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine($"file sealed class {reg.MetadataClassName} : global::CsEval.Aot.IAotTypeMetadata");
        sb.AppendLine("{");

        EmitTypeProperty(sb, reg);
        EmitTryGetProperty(sb, reg);
        EmitTrySetProperty(sb, reg);
        EmitTryGetField(sb, reg);
        EmitTrySetField(sb, reg);
        EmitTryGetIndex(sb, reg);
        EmitTrySetIndex(sb, reg);
        EmitTryGetStaticProperty(sb, reg);
        EmitTryGetStaticField(sb, reg);
        EmitTryCreateInstance(sb, reg);
        EmitTryInvokeMethod(sb, reg);
        EmitTryInvokeStaticMethod(sb, reg);

        sb.AppendLine("}");
        return sb.ToString();
    }

    public static string? EmitGenericInstantiations(ImmutableArray<TypeRegistrationModel> registrations)
    {
        var closedGenerics = registrations.Where(r => r.IsClosedGeneric).ToArray();
        if (closedGenerics.Length == 0)
            return null;

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("file static class GenericInstantiations");
        sb.AppendLine("{");

        var seenFields = new HashSet<string>();
        foreach (var reg in closedGenerics)
        {
            var fieldName = "_" + SanitizeFieldName(reg.TypeFullName);
            if (!seenFields.Add(fieldName))
                continue;
            sb.AppendLine($"    static readonly global::System.Type {fieldName} = typeof({reg.TypeFullName});");
        }

        sb.AppendLine("}");
        return sb.ToString();
    }

    private static void EmitTypeProperty(StringBuilder sb, TypeRegistrationModel reg)
    {
        sb.AppendLine($"    public global::System.Type Type => typeof({reg.TypeFullName});");
        sb.AppendLine();
    }

    private static void EmitTryGetProperty(StringBuilder sb, TypeRegistrationModel reg)
    {
        var instanceProps = reg.Properties.Where(p => p is { IsStatic: false, CanRead: true }).ToArray();

        sb.AppendLine("    public bool TryGetProperty(string name, object instance, out object? value)");
        sb.AppendLine("    {");

        if (instanceProps.Length > 0)
        {
            sb.AppendLine($"        var typed = ({reg.TypeFullName})instance;");
            sb.AppendLine("        switch (name)");
            sb.AppendLine("        {");
            foreach (var prop in instanceProps)
                sb.AppendLine($"            case \"{prop.Name}\": value = typed.{prop.Name}; return true;");
            sb.AppendLine("            default: value = default; return false;");
            sb.AppendLine("        }");
        }
        else
        {
            sb.AppendLine("        value = default;");
            sb.AppendLine("        return false;");
        }

        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static void EmitTrySetProperty(StringBuilder sb, TypeRegistrationModel reg)
    {
        var writableProps = reg.Properties.Where(p => p is { IsStatic: false, CanWrite: true }).ToArray();

        sb.AppendLine("    public bool TrySetProperty(string name, object instance, object? value)");
        sb.AppendLine("    {");

        if (writableProps.Length > 0)
        {
            sb.AppendLine($"        var typed = ({reg.TypeFullName})instance;");
            sb.AppendLine("        switch (name)");
            sb.AppendLine("        {");
            foreach (var prop in writableProps)
                sb.AppendLine($"            case \"{prop.Name}\": typed.{prop.Name} = ({prop.TypeFullName})value!; return true;");
            sb.AppendLine("            default: return false;");
            sb.AppendLine("        }");
        }
        else
        {
            sb.AppendLine("        return false;");
        }

        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static void EmitTryGetField(StringBuilder sb, TypeRegistrationModel reg)
    {
        var instanceFields = reg.Fields.Where(f => !f.IsStatic).ToArray();

        sb.AppendLine("    public bool TryGetField(string name, object instance, out object? value)");
        sb.AppendLine("    {");

        if (instanceFields.Length > 0)
        {
            sb.AppendLine($"        var typed = ({reg.TypeFullName})instance;");
            sb.AppendLine("        switch (name)");
            sb.AppendLine("        {");
            foreach (var field in instanceFields)
                sb.AppendLine($"            case \"{field.Name}\": value = typed.{field.Name}; return true;");
            sb.AppendLine("            default: value = default; return false;");
            sb.AppendLine("        }");
        }
        else
        {
            sb.AppendLine("        value = default;");
            sb.AppendLine("        return false;");
        }

        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static void EmitTrySetField(StringBuilder sb, TypeRegistrationModel reg)
    {
        var writableFields = reg.Fields.Where(f => f is { IsStatic: false, IsReadOnly: false }).ToArray();

        sb.AppendLine("    public bool TrySetField(string name, object instance, object? value)");
        sb.AppendLine("    {");

        if (writableFields.Length > 0)
        {
            sb.AppendLine($"        var typed = ({reg.TypeFullName})instance;");
            sb.AppendLine("        switch (name)");
            sb.AppendLine("        {");
            foreach (var field in writableFields)
                sb.AppendLine($"            case \"{field.Name}\": typed.{field.Name} = ({field.TypeFullName})value!; return true;");
